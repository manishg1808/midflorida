<!-- Interactive Script for FAQs and Tabs -->
<script>
document.addEventListener('DOMContentLoaded', function() {
    // 1. FAQ Accordion Toggle
    const faqItems = document.querySelectorAll('.cm-faq-item');
    faqItems.forEach(item => {
        const question = item.querySelector('.cm-faq-question');
        question.addEventListener('click', () => {
            const isOpen = item.classList.contains('open');
            faqItems.forEach(i => i.classList.remove('open'));
            if (!isOpen) {
                item.classList.add('open');
            }
        });
    });

    // 2. Subgrade Switcher Topics for 3-5
    const subgradeBtns = document.querySelectorAll('.cm-subgrade-tab-btn');
    const topicList = document.getElementById('g35-topic-list');
    
    const g35Topics = {
        'g35-g3': [
            'Multiplication & Division Fact Families',
            'Understanding Fractions & Number Lines',
            'Area, Perimeter & 2D Geometry',
            'Time, Liquid Volume & Mass',
            'Bar Graphs & Line Plots'
        ],
        'g35-g4': [
            'Multi-Digit Multiplication & Long Division',
            'Fraction Equivalence & Operations (+, -)',
            'Decimals & Place Value Extensions',
            'Angles & Geometric Classifications',
            'Multi-Step Real-World Word Problems'
        ],
        'g35-g5': [
            'Operations with Decimals & Fractions (×, ÷)',
            'Volume & 3D Spatial Geometry',
            'Coordinate Graphing & Numerical Patterns',
            'Order of Operations & Pre-Algebra Expressions',
            'Word Problem Logic & Mathematical Modeling'
        ]
    };

    subgradeBtns.forEach(btn => {
        btn.addEventListener('click', function() {
            subgradeBtns.forEach(b => b.classList.remove('active'));
            this.classList.add('active');
            const target = this.getAttribute('data-target');
            const topics = g35Topics[target] || g35Topics['g35-g3'];
            
            let html = '';
            topics.forEach((t, idx) => {
                html += `
                <div class="cm-topic-row">
                    <span class="cm-topic-num">${idx + 1}</span>
                    <span class="cm-topic-name">${t}</span>
                </div>`;
            });
            html += `
            <div style="padding-left: 56px; margin-top: 8px;">
                <a href="javascript:void(0);" class="open-trial-modal" style="font-weight: 700; color: #1E293B; text-decoration: underline; font-size: 0.95rem;">
                    View Detailed Curriculum
                </a>
            </div>`;
            topicList.innerHTML = html;
        });
    });

    // 3. Ownership Role Switcher
    const roleBtns = document.querySelectorAll('.cm-ownership-btn');
    const displayBox = document.getElementById('ownership-display');
    const roleContent = {
        'students': {
            icon: 'fa-lightbulb',
            color: '#10B981',
            title: 'Mastering Math Without Rote Drills',
            desc: 'Students gain genuine understanding of fractions and decimals through interactive models. They lead 64% of the conversation, building articulation and genuine problem-solving grit.'
        },
        'parents': {
            icon: 'fa-heart',
            color: '#2563EB',
            title: 'Confidence Replaces Homework Tears',
            desc: 'Grade 3–5 math often creates friction at home when parents have busy schedules. Our dedicated tutors handle the explanations, homework clarification, and exam practice so you can enjoy family time without math battles.'
        },
        'teachers': {
            icon: 'fa-chalkboard-teacher',
            color: '#8B5CF6',
            title: 'Tailored Pacing for Every Thinker',
            desc: 'Whether a student needs extra time on long division or is ready for Math Kangaroo Olympiad questions, our mentors adjust lesson plans in real-time to match each student’s cognitive speed.'
        }
    };

    roleBtns.forEach(btn => {
        btn.addEventListener('click', function() {
            roleBtns.forEach(b => b.classList.remove('active'));
            this.classList.add('active');
            const role = this.getAttribute('data-role');
            const data = roleContent[role];
            displayBox.innerHTML = `
            <div style="display: flex; gap: 32px; align-items: center; flex-wrap: wrap;">
                <div style="width: 72px; height: 72px; border-radius: 50%; background: #EFF6FF; color: ${data.color}; display: flex; align-items: center; justify-content: center; font-size: 2rem; flex-shrink: 0;">
                    <i class="fas ${data.icon}"></i>
                </div>
                <div style="flex: 1; min-width: 260px;">
                    <h3 style="font-size: 1.5rem; font-weight: 700; color: #0F172A; margin-bottom: 8px;">${data.title}</h3>
                    <p style="font-size: 1.05rem; color: #475569; line-height: 1.6;">${data.desc}</p>
                </div>
            </div>`;
        });
    });
});
</script>

